// OpenAPIToolSummary provides a direct, agent-friendly view of an MCP tool
// alongside the standard OpenAPI 3.1.0 paths and component schemas.
type OpenAPIToolSummary struct {
	Name        string         `json:"name"`
	Description string         `json:"description"`
	Operations  string         `json:"operations,omitempty"`
	InputSchema map[string]any `json:"inputSchema"`
}

func collectLiveMCPTools() []mcp.Tool {
	reg := RegistryMCPServer("default", func(context.Context) (any, error) {
		return nil, nil
	}, func(context.Context, string, string, string) (*server.MCPServer, error) {
		return nil, nil
	}, func(context.Context, string, string, string, string) (any, error) {
		return nil, nil
	})
	AddFileReservationTool(reg, "default", func(context.Context, string, string, string, string, string, []string) ([]FileReservation, error) {
		return nil, nil
	})
	boot := ProjectBootstrapMCPServer(nil, "", "")

	byName := map[string]mcp.Tool{}
	for k, def := range reg.ListTools() {
		byName[k] = def.Tool
	}
	for k, def := range boot.ListTools() {
		if _, exists := byName[k]; !exists {
			byName[k] = def.Tool
		}
	}

	names := make([]string, 0, len(byName))
	for name := range byName {
		names = append(names, name)
	}
	sort.Strings(names)

	out := make([]mcp.Tool, 0, len(names))
	for _, name := range names {
		out = append(out, byName[name])
	}
	return out
}

func toolSchemaMap(t mcp.Tool) (map[string]any, string) {
	props := map[string]any{}
	var opsDesc string
	for k, v := range t.InputSchema.Properties {
		props[k] = v
		if k == "operation" {
			if m, ok := v.(map[string]any); ok {
				if d, ok := m["description"].(string); ok {
					opsDesc = d
				}
			}
		}
	}
	schemaType := t.InputSchema.Type
	if schemaType == "" {
		schemaType = "object"
	}
	schema := map[string]any{
		"type":        schemaType,
		"description": t.Description,
		"properties":  props,
	}
	if len(t.InputSchema.Required) > 0 {
		schema["required"] = t.InputSchema.Required
	}
	return schema, opsDesc
}

// BuildOpenAPISpec dynamically constructs an OpenAPI 3.1.0 specification and
// MCP tool catalog directly from the live registered MCP tool definitions.
// If toolFilter is non-empty, only matching tools are included.
func BuildOpenAPISpec(toolFilter string) map[string]any {
	filter := strings.ToLower(strings.TrimSpace(toolFilter))
	tools := collectLiveMCPTools()

	paths := map[string]any{
		"/openapi.json": map[string]any{
			"get": map[string]any{
				"operationId": "getOpenAPISpec",
				"summary":     "Autogenerated OpenAPI 3.1.0 specification and live MCP tool schemas",
				"parameters": []map[string]any{
					{
						"name":        "tool",
						"in":          "query",
						"required":    false,
						"description": "Optional MCP tool name filter (e.g. gossip_send, gossip_sync, gossip_projects)",
						"schema":      map[string]any{"type": "string"},
					},
				},
				"responses": map[string]any{
					"200": map[string]any{
						"description": "OpenAPI 3.1.0 document with live MCP tool schemas and recovery guidance",
					},
				},
			},
		},
	}
	schemas := map[string]any{}
	summaries := make([]OpenAPIToolSummary, 0, len(tools))

	for _, t := range tools {
		if filter != "" && !strings.Contains(strings.ToLower(t.Name), filter) {
			continue
		}
		schema, opsDesc := toolSchemaMap(t)
		schemas[t.Name] = schema
		summaries = append(summaries, OpenAPIToolSummary{
			Name:        t.Name,
			Description: t.Description,
			Operations:  opsDesc,
			InputSchema: schema,
		})

		opObj := map[string]any{
			"operationId": t.Name,
			"summary":     t.Description,
			"requestBody": map[string]any{
				"required": true,
				"content": map[string]any{
					"application/json": map[string]any{
						"schema": map[string]any{
							"$ref": "#/components/schemas/" + t.Name,
						},
					},
				},
			},
			"responses": map[string]any{
				"200": map[string]any{
					"description": "MCP CallToolResult JSON response",
				},
			},
		}
		if opsDesc != "" {
			opObj["x-supported-operations"] = opsDesc
		}
		paths["/mcp/tools/"+t.Name] = map[string]any{
			"post": opObj,
		}
	}

	return map[string]any{
		"openapi": "3.1.0",
		"info": map[string]any{
			"title":       "Gossip Coordination & MCP Tool API",
			"version":     "0.2.0",
			"description": "Autogenerated OpenAPI 3.1.0 specification and live MCP tool schemas for Gossip multi-agent coordination. Generated at runtime from the registered MCP server definitions so agents always see up-to-date parameters, operations, and recovery guidance.",
		},
		"x-agent-guidance": map[string]any{
			"discovery_endpoints": []string{
				"GET /openapi.json",
				"GET /api/openapi.json",
				"GET /v1/openapi.json",
				"MCP tool: gossip_openapi (optional argument: tool=\"<tool_name>\")",
				"MCP tool: gossip_projects(operation=\"openapi\", tool=\"<tool_name>\")",
				"CLI: gossip openapi [--tool <tool_name>]",
			},
			"project_selection_and_join": map[string]any{
				"inspect":    "Call gossip_projects(operation=\"list\") to view enrolled connections and (on local machines only) local_available projects.",
				"join_local": "For local_available projects only, ask the human user for explicit permission first, then call gossip_projects(operation=\"join\", project=\"<id_or_name>\", user_permission=true, permission_note=\"...\"). Never auto-join without permission; LAN/FRP connections cannot list or self-join other projects.",
				"routing":    "Pass project=\"<project_id_or_name>\" and profile=\"<profile>\" on tool calls when multiple connections exist.",
			},
			"messaging_and_adaptive_polling": map[string]any{
				"delta_reads":         "Omit last_read_hash on the first read to fetch visible history; pass last_read_hash (or last_msg_hash) on subsequent gossip_sync(operation=\"inbox\"), gossip_read(operation=\"messages\"), or gossip_channel(operation=\"messages\") calls to receive only 1 previous anchor message plus newer messages.",
				"dynamic_poll_timer":  "Start recurring poll timers at 30s min; pass idle_polls to gossip_sync(operation=\"inbox\"). After 3 consecutive idle/no-ack checks, recommended_poll_seconds doubles up to 900s (15m max) and resets to 30s immediately on new activity.",
				"working_mode":        "Acknowledge received tasks with gossip_read(operation=\"acknowledge\", message_id=\"...\", mode=\"working\", checkAfter=\"4m\") so peers wait until your ETA.",
				"planning_mode":       "Include mode=\"planning\" (or \"decision\") and checkAfter (e.g. \"45s\", \"2m\") on every gossip_send or gossip_channel(operation=\"send\") message to negotiate turn cadence.",
				"communication_mode":  "Include mode=\"communication\", ttl (e.g. \"10m\"), and rto (e.g. \"60s\") on messages; unacknowledged outbound messages past RTO before TTL expiry appear in gossip_sync(operation=\"inbox\") under rto_due_messages with TCP-like doubled next_rto_seconds.",
				"explicit_peer_modes": "Use gossip_agents(operation=\"set_mode\", mode=\"working|planning|decision|communication\", checkAfter=\"...\", ttl=\"...\", rto=\"...\") to advertise mode or gossip_agents(operation=\"modes\") to inspect peers.",
			},
		},
		"paths": paths,
		"components": map[string]any{
			"schemas": schemas,
		},
		"x-mcp-tools": summaries,
	}
}

func serveOpenAPIHTTP(w http.ResponseWriter, r *http.Request) {
	spec := BuildOpenAPISpec(r.URL.Query().Get("tool"))
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.WriteHeader(http.StatusOK)
	enc := json.NewEncoder(w)
	enc.SetIndent("", "  ")
	_ = enc.Encode(spec)
}
