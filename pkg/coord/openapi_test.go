package coord_test

import (
	"context"
	"encoding/json"
	"net/http"
	"net/http/httptest"
	"testing"

	"github.com/mark3labs/mcp-go/mcp"
	"github.com/mark3labs/mcp-go/server"
	"github.com/tasmirz/gossip/pkg/coord"
)

func TestOpenAPIEndpointAndMCPToolAutogeneratedSchemas(t *testing.T) {
	s, _, project, owner, _ := setup(t)
	ctx := context.Background()

	// 1. Direct BuildOpenAPISpec returns OpenAPI 3.1.0 with all live tools and guidance.
	spec := coord.BuildOpenAPISpec("")
	if spec["openapi"] != "3.1.0" {
		t.Fatalf("expected openapi 3.1.0, got %v", spec["openapi"])
	}
	paths, ok := spec["paths"].(map[string]any)
	if !ok {
		t.Fatalf("missing paths map in openapi spec")
	}
	for _, wantPath := range []string{
		"/openapi.json",
		"/mcp/tools/gossip_send",
		"/mcp/tools/gossip_sync",
		"/mcp/tools/gossip_read",
		"/mcp/tools/gossip_projects",
		"/mcp/tools/gossip_agents",
		"/mcp/tools/gossip_file_locks",
		"/mcp/tools/gossip_create_project",
		"/mcp/tools/gossip_openapi",
	} {
		if _, exists := paths[wantPath]; !exists {
			t.Fatalf("expected autogenerated path %s in OpenAPI spec", wantPath)
		}
	}

	// Verify filtered BuildOpenAPISpec("gossip_send") includes checkAfter, mode, ttl, rto properties.
	filtered := coord.BuildOpenAPISpec("gossip_send")
	comp := filtered["components"].(map[string]any)["schemas"].(map[string]any)
	if len(comp) != 1 {
		t.Fatalf("expected 1 filtered schema for gossip_send, got %d", len(comp))
	}
	sendSchema := comp["gossip_send"].(map[string]any)
	props := sendSchema["properties"].(map[string]any)
	for _, prop := range []string{"checkAfter", "mode", "ttl", "rto", "project", "profile"} {
		if _, ok := props[prop]; !ok {
			t.Fatalf("expected live property %q in gossip_send schema, got %+v", prop, props)
		}
	}

	// 2. WebHandler GET /openapi.json and GET /api/openapi.json?tool=gossip_sync
	web := coord.NewWebHandler(s)
	for _, path := range []string{"/openapi.json", "/api/openapi.json?tool=gossip_sync", "/v1/openapi.json"} {
		req := httptest.NewRequest(http.MethodGet, "http://127.0.0.1:47281"+path, nil)
		req.RemoteAddr = "127.0.0.1:54321"
		rec := httptest.NewRecorder()
		web.ServeHTTP(rec, req)
		if rec.Code != http.StatusOK {
			t.Fatalf("GET %s status=%d body=%s", path, rec.Code, rec.Body.String())
		}
		var doc map[string]any
		if err := json.Unmarshal(rec.Body.Bytes(), &doc); err != nil {
			t.Fatalf("GET %s invalid JSON: %v", path, err)
		}
		if doc["openapi"] != "3.1.0" {
			t.Fatalf("GET %s expected openapi=3.1.0, got %v", path, doc["openapi"])
		}
	}

	// 3. MCP tool gossip_openapi works on project MCPServer AND on RegistryMCPServer even without a valid project resolution.
	mcpSrv := coord.MCPServer(s, project.ID, owner.Token)
	res, err := mcpSrv.GetTool("gossip_openapi").Handler(ctx, mcp.CallToolRequest{Params: mcp.CallToolParams{
		Name:      "gossip_openapi",
		Arguments: map[string]any{"tool": "gossip_read"},
	}})
	if err != nil || res.IsError {
		t.Fatalf("gossip_openapi on MCPServer failed: err=%v res=%+v", err, res)
	}
	var readSpec map[string]any
	if err := json.Unmarshal([]byte(res.Content[0].(mcp.TextContent).Text), &readSpec); err != nil {
		t.Fatal(err)
	}
	readSchemas := readSpec["components"].(map[string]any)["schemas"].(map[string]any)
	if _, ok := readSchemas["gossip_read"]; !ok {
		t.Fatalf("expected gossip_read schema in filtered gossip_openapi output")
	}

	regSrv := coord.RegistryMCPServer("default", func(context.Context) (any, error) {
		return nil, nil
	}, func(context.Context, string, string, string) (*server.MCPServer, error) {
		t.Fatal("gossip_openapi should not require project resolution")
		return nil, nil
	})
	res, err = regSrv.ListTools()["gossip_openapi"].Handler(ctx, mcp.CallToolRequest{Params: mcp.CallToolParams{
		Name:      "gossip_openapi",
		Arguments: map[string]any{"tool": "gossip_agents"},
	}})
	if err != nil || res.IsError {
		t.Fatalf("gossip_openapi on RegistryMCPServer failed: err=%v res=%+v", err, res)
	}
	res, err = regSrv.ListTools()["gossip_projects"].Handler(ctx, mcp.CallToolRequest{Params: mcp.CallToolParams{
		Name:      "gossip_projects",
		Arguments: map[string]any{"operation": "openapi", "tool": "gossip_agents"},
	}})
	if err != nil || res.IsError {
		t.Fatalf("gossip_projects(operation=openapi) failed: err=%v res=%+v", err, res)
	}
}
