// DetectLocalLANIPs enumerates non-loopback local network interfaces to identify accessible LAN endpoints.
func DetectLocalLANIPs() []string {
	var ips []string
	ifaces, err := net.Interfaces()
	if err != nil {
		return ips
	}

	for _, iface := range ifaces {
		// Ignore interfaces that are down or are loopbacks
		if iface.Flags&net.FlagUp == 0 || iface.Flags&net.FlagLoopback != 0 {
			continue
		}
		addrs, err := iface.Addrs()
		if err != nil {
			continue
		}
		for _, addr := range addrs {
			var ip net.IP
			switch v := addr.(type) {
			case *net.IPNet:
				ip = v.IP
			case *net.IPAddr:
				ip = v.IP
			}
			if ip == nil || ip.IsLoopback() {
				continue
			}
			// Only IPv4 for clean readability
			if ip.To4() != nil {
				ips = append(ips, ip.String())
			}
		}
	}
	return ips
}

// SaveTunnelState saves the tunnel state to tunnel.json in storageDir with strict 0600 file permissions.
func SaveTunnelState(storageDir string, state TunnelState) error {
	if storageDir == "" {
		storageDir = ".local/gossip"
	}
	if err := os.MkdirAll(storageDir, 0755); err != nil {
		return fmt.Errorf("failed to create directory %s: %w", storageDir, err)
	}

	state.UpdatedAt = time.Now()
	if state.StartedAt.IsZero() && state.Active {
		state.StartedAt = state.UpdatedAt
	}

	data, err := json.MarshalIndent(state, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal tunnel state: %w", err)
	}

	filePath := filepath.Join(storageDir, TunnelStateFileName)
	// Write with 0600 so passwords/tokens cannot be read by other local users
	return os.WriteFile(filePath, data, 0600)
}

// LoadTunnelState reads tunnel.json from storageDir. If not found, returns inactive state.
func LoadTunnelState(storageDir string) (*TunnelState, error) {
	if storageDir == "" {
		storageDir = ".local/gossip"
	}
	filePath := filepath.Join(storageDir, TunnelStateFileName)
	data, err := os.ReadFile(filePath)
	if err != nil {
		if os.IsNotExist(err) {
			return &TunnelState{
				Active:      false,
				Type:        "none",
				AuthEnabled: false,
			}, nil
		}
		return nil, err
	}

	var state TunnelState
	if err := json.Unmarshal(data, &state); err != nil {
		return nil, fmt.Errorf("failed to parse %s: %w", filePath, err)
	}
	return &state, nil
}

// ClearTunnelState removes tunnel.json or marks it inactive.
func ClearTunnelState(storageDir string) error {
	if storageDir == "" {
		storageDir = ".local/gossip"
	}
	filePath := filepath.Join(storageDir, TunnelStateFileName)
	_ = os.Remove(filePath)
	return nil
}
