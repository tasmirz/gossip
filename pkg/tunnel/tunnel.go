// Tunnel state file name inside .local/gossip
const TunnelStateFileName = "tunnel.json"

// FRPClientConfig defines the parameters for generating client FRP configs.
type FRPClientConfig struct {
	ServerAddr     string   `json:"server_addr"`
	ServerPort     int      `json:"server_port"`
	AuthToken      string   `json:"auth_token"`
	ProxyName      string   `json:"proxy_name"`
	ProxyType      string   `json:"proxy_type"` // "http" or "tcp"
	LocalIP        string   `json:"local_ip"`
	LocalPort      int      `json:"local_port"`
	RemotePort     int      `json:"remote_port,omitempty"` // For TCP proxying
	CustomDomains  []string `json:"custom_domains,omitempty"`
	Subdomain      string   `json:"subdomain,omitempty"`
	HTTPUser       string   `json:"http_user,omitempty"` // Mandatory Basic Auth user
	HTTPPassword   string   `json:"http_password,omitempty"`
	UseEncryption  bool     `json:"use_encryption"`
	UseCompression bool     `json:"use_compression"`
}

// FRPServerConfig defines parameters for generating server FRP configs (frps).
type FRPServerConfig struct {
	BindPort      int    `json:"bind_port"`
	AuthToken     string `json:"auth_token"`
	VhostHTTPPort int    `json:"vhost_http_port,omitempty"`
	DashboardPort int    `json:"dashboard_port,omitempty"`
	DashboardUser string `json:"dashboard_user,omitempty"`
	DashboardPwd  string `json:"dashboard_pwd,omitempty"`
}

// TunnelState tracks the active tunnel configuration and runtime state.
type TunnelState struct {
	Active         bool      `json:"active"`
	Type           string    `json:"type"` // "frp", "lan", "none"
	ServerAddr     string    `json:"server_addr,omitempty"`
	RemoteEndpoint string    `json:"remote_endpoint,omitempty"`
	LocalIP        string    `json:"local_ip"`
	LocalPort      int       `json:"local_port"`
	RemotePort     int       `json:"remote_port,omitempty"`
	AuthEnabled    bool      `json:"auth_enabled"`
	AuthUser       string    `json:"auth_user,omitempty"`
	AuthPassMasked string    `json:"auth_pass_masked,omitempty"`
	ConfigPath     string    `json:"config_path,omitempty"`
	StartedAt      time.Time `json:"started_at"`
	UpdatedAt      time.Time `json:"updated_at"`
}

// MaskSecret masks sensitive credentials for safe logging and display.
func MaskSecret(secret string) string {
	if secret == "" {
		return ""
	}
	if len(secret) <= 4 {
		return "********"
	}
	prefixLen := 3
	if len(secret) < 8 {
		prefixLen = 2
	}
	return secret[:prefixLen] + "..." + strings.Repeat("*", 6)
}

// ValidateCredentials checks that username and password meet minimum security constraints.
func ValidateCredentials(user, pass string) error {
	if strings.TrimSpace(user) == "" {
		return errors.New("authentication username cannot be empty")
	}
	if len(user) < 3 {
		return errors.New("authentication username must be at least 3 characters")
	}
	if strings.ContainsAny(user, " :@/\r\n\t") {
		return errors.New("authentication username contains invalid characters")
	}
	if len(pass) < 6 {
		return errors.New("authentication password must be at least 6 characters for protected access")
	}
	return nil
}

// SecureCompare performs a constant-time comparison of two strings to prevent timing attacks.
func SecureCompare(a, b string) bool {
	return subtle.ConstantTimeCompare([]byte(a), []byte(b)) == 1
}

