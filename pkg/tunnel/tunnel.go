// GenerateFRPCTOML produces a modern v0.52+ FRP client configuration in TOML.
func GenerateFRPCTOML(cfg FRPClientConfig) string {
	var b strings.Builder
	b.WriteString("# Gossip FRP Client Configuration (v0.52+ TOML format)\n")
	b.WriteString("# Generated by Gossip Multi-Agent Mesh\n")
	b.WriteString(fmt.Sprintf("serverAddr = %q\n", cfg.ServerAddr))
	b.WriteString(fmt.Sprintf("serverPort = %d\n", cfg.ServerPort))
	if cfg.AuthToken != "" {
		b.WriteString(fmt.Sprintf("auth.token = %q\n", cfg.AuthToken))
	}
	b.WriteString("\n[[proxies]]\n")
	b.WriteString(fmt.Sprintf("name = %q\n", cfg.ProxyName))
	b.WriteString(fmt.Sprintf("type = %q\n", cfg.ProxyType))
	localIP := cfg.LocalIP
	if localIP == "" {
		localIP = "127.0.0.1"
	}
	b.WriteString(fmt.Sprintf("localIP = %q\n", localIP))
	b.WriteString(fmt.Sprintf("localPort = %d\n", cfg.LocalPort))

	if cfg.ProxyType == "http" {
		if len(cfg.CustomDomains) > 0 {
			var quoted []string
			for _, d := range cfg.CustomDomains {
				quoted = append(quoted, fmt.Sprintf("%q", d))
			}
			b.WriteString(fmt.Sprintf("customDomains = [%s]\n", strings.Join(quoted, ", ")))
		}
		if cfg.Subdomain != "" {
			b.WriteString(fmt.Sprintf("subdomain = %q\n", cfg.Subdomain))
		}
		// Mandatory Basic Auth Protection on FRP ingress
		if cfg.HTTPUser != "" && cfg.HTTPPassword != "" {
			b.WriteString(fmt.Sprintf("httpUser = %q\n", cfg.HTTPUser))
			b.WriteString(fmt.Sprintf("httpPassword = %q\n", cfg.HTTPPassword))
		}
	} else if cfg.ProxyType == "tcp" {
		remPort := cfg.RemotePort
		if remPort == 0 {
			remPort = cfg.LocalPort
		}
		b.WriteString(fmt.Sprintf("remotePort = %d\n", remPort))
	}

	if cfg.UseEncryption {
		b.WriteString("transport.useEncryption = true\n")
	}
	if cfg.UseCompression {
		b.WriteString("transport.useCompression = true\n")
	}

	return b.String()
}

